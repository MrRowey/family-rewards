import { z } from "zod";

const id = z.string().min(1).max(100);
const date = z.iso.datetime().transform((value) => new Date(value));

export const backupSchema = z.object({
  version: z.enum(["1.0", "2.0", "3.0"]),
  data: z.object({
    children: z.array(z.object({
      id: id,
      name: z.string().max(20000),
      avatar: z.string().max(20000).optional(),
      avatarTheme: z.string().max(20000).nullable().optional(),
      avatarConfig: z.string().max(20000).nullable().optional(),
      stars: z.number().int().min(0).max(2147483647).optional(),
      avatarCoins: z.number().int().min(0).max(2147483647).optional(),
      avatarCoinDebt: z.number().int().min(0).max(2147483647).optional(),
      starDebt: z.number().int().min(0).max(2147483647).optional(),
      xp: z.number().int().min(0).max(2147483647).optional(),
      rewardedLevel: z.number().int().min(1).max(2147483647).optional(),
      kioskMode: z.string().max(32).optional(),
      dob: date,
      createdAt: date.optional(),
    })).max(100000),
    tasks: z.array(z.object({
      category: z.string().max(20000).nullable().optional(),
      id: id,
      title: z.string().max(20000),
      icon: z.string().max(20000).optional(),
      imageURL: z.string().max(20000).nullable().optional(),
      starValue: z.number().int().min(0).max(2147483647).optional(),
      minAge: z.number().int().min(0).max(2147483647).optional(),
      maxAge: z.number().int().min(0).max(2147483647).optional(),
      createdAt: date.optional(),
    })).max(100000),
    subSteps: z.array(z.object({
      id: id,
      taskId: id,
      title: z.string().max(20000),
      order: z.number().int().min(0).max(2147483647).optional(),
    })).max(100000),
    rewards: z.array(z.object({
      category: z.string().max(20000).nullable().optional(),
      id: id,
      title: z.string().max(20000),
      description: z.string().max(20000).nullable().optional(),
      icon: z.string().max(20000).optional(),
      imageURL: z.string().max(20000).nullable().optional(),
      starCost: z.number().int().min(0).max(2147483647).optional(),
      monthlyStock: z.number().int().min(0).max(2147483647).optional(),
      currentStock: z.number().int().min(0).max(2147483647).optional(),
      minAge: z.number().int().min(0).max(2147483647).optional(),
      maxAge: z.number().int().min(0).max(2147483647).optional(),
      isVisible: z.boolean().optional(),
      isArchived: z.boolean().optional(),
      isGroup: z.boolean().optional(),
      targetMonth: z.number().int().min(1).max(12).nullable().optional(),
      createdAt: date.optional(),
    })).max(100000),
    assignments: z.array(z.object({
      id: id,
      childId: id,
      taskId: id,
      dayOfWeek: z.number().int().min(0).max(6),
      repeatInterval: z.number().int().min(0).max(2147483647).optional(),
      startDate: date.optional(),
      endDate: date.nullable().optional(),
    })).max(100000),
    completions: z.array(z.object({
      id: id,
      childId: id,
      taskId: id,
      status: z.enum(["PENDING", "APPROVED", "DECLINED", "REVERSED"]).optional(),
      forDate: date,
      completedAt: date.optional(),
      starsAwarded: z.number().int().min(0).max(2147483647).nullable().optional(),
    })).max(100000),
    redemptions: z.array(z.object({
      id: id,
      childId: id,
      rewardId: id,
      status: z.enum(["PENDING", "APPROVED", "DECLINED", "REFUNDED"]).optional(),
      stockReserved: z.boolean().optional(),
      refundState: z.enum(["PENDING", "APPROVED", "DECLINED"]).nullable().optional(),
      starCostAtClaim: z.number().int().min(0).max(2147483647).nullable().optional(),
      requestedAt: date.optional(),
    })).max(100000),
    logs: z.array(z.object({
      id: id,
      actor: z.string().max(20000),
      actorType: z.string().max(20000),
      action: z.string().max(20000),
      details: z.string().max(20000),
      createdAt: date.optional(),
    })).max(100000),
    rewardAssignments: z.array(z.object({
      id: id,
      childId: id,
      rewardId: id,
    })).max(100000).default([]),
    shopPlans: z.array(z.object({
      childId: id,
      year: z.number().int().min(0).max(2147483647),
      month: z.number().int().min(1).max(12),
      rewardIds: z.array(id).max(1000),
    })).max(100000).default([]),
    groupPledges: z.array(z.object({
      id: id,
      rewardId: id,
      childId: id,
      stars: z.number().int().min(0).max(2147483647),
      createdAt: date.optional(),
    })).max(100000).default([]),
    badges: z.array(z.object({
      id: id,
      title: z.string().max(20000),
      description: z.string().max(20000),
      icon: z.string().max(20000),
      ruleType: z.string().max(20000),
      threshold: z.number().int().min(0).max(2147483647).optional(),
      unlockedItem: z.string().max(20000).nullable().optional(),
      createdAt: date.optional(),
    })).max(100000).default([]),
    childBadges: z.array(z.object({
      id: id,
      childId: id,
      badgeId: id,
      awardedAt: date.optional(),
    })).max(100000).default([]),
    avatarUnlocks: z.array(z.object({
      id, childId: id, theme: z.string().max(80),
      component: z.string().max(100), variant: z.string().max(100),
      cost: z.number().int().min(0).max(2147483647),
      createdAt: date.optional(),
    })).max(100000).default([]),
    xpLedger: z.array(z.object({
      id, childId: id, sourceKey: z.string().max(160),
      delta: z.number().int().min(-2147483647).max(2147483647),
      stars: z.number().int().min(-2147483647).max(2147483647),
      minFactor: z.number().int().min(0).max(100),
      maxFactor: z.number().int().min(0).max(100),
      createdAt: date.optional(),
    })).max(100000).default([]),
    avatarCurrencyLedger: z.array(z.object({
      id, childId: id, sourceKey: z.string().max(160),
      delta: z.number().int().min(-2147483647).max(2147483647),
      debtDelta: z.number().int().min(-2147483647).max(2147483647),
      reason: z.string().max(80),
      createdAt: date.optional(),
    })).max(100000).default([]),
    avatarMilestones: z.array(z.object({
      id, childId: id,
      level: z.number().int().min(10).max(100000),
      policyVersion: z.number().int().min(1).max(1000),
      bonusCoins: z.number().int().min(0).max(2147483647),
      cosmeticKey: z.string().max(100),
      createdAt: date.optional(),
    })).max(100000).default([]),
  }),
});
